"use client";

import { supabase } from "./supabase";
import { CHECKLIST } from "@/data/document-checklist";

/**
 * Counselor groups.
 *
 * A counselor creates a group and shares its join code; a student enters the
 * code to join. ENTERING THE CODE IS THE CONSENT — the student's own request
 * creates the membership row, through `ah_join_group()`, a SECURITY DEFINER
 * function. That function exists because `ah_groups` is deliberately not
 * readable by a student who has not joined: otherwise anyone signed in could
 * enumerate every group and every join code.
 *
 * Membership grants the counselor read access through one place only —
 * `ah_is_counselor_of()` — so a group reaches all nine tables and the files in
 * storage at once, without a second copy of the rule.
 */

export type GroupResult<T> = { ok: true; value: T } | { ok: false; error: string };

export interface GroupMember {
  studentId: string;
  name: string;
  joinedAt: string;
}

export interface Group {
  id: string;
  name: string;
  joinCode: string;
  ownerName?: string;
  createdAt: string;
  members: GroupMember[];
}

const uid = async () => {
  const sb = supabase();
  if (!sb) return null;
  const { data } = await sb.auth.getUser();
  return data.user?.id ?? null;
};

const toGroup = (r: {
  id: string;
  name: string;
  join_code: string;
  created_at: string;
}): Group => ({ id: r.id, name: r.name, joinCode: r.join_code, createdAt: r.created_at, members: [] });

/** A counselor creates a group; the join code is generated by the database. */
export async function createGroup(name: string): Promise<GroupResult<Group>> {
  const sb = supabase();
  if (!sb) return { ok: false, error: "not configured" };
  const me = await uid();
  if (!me) return { ok: false, error: "not signed in" };
  if (!name.trim()) return { ok: false, error: "give the group a name" };

  const { data, error } = await sb
    .from("ah_groups")
    .insert({ owner_id: me, name: name.trim() })
    .select("id, name, join_code, created_at")
    .single();
  return error ? { ok: false, error: error.message } : { ok: true, value: toGroup(data) };
}

/** Groups this counselor owns, with the students who have joined. */
export async function listMyGroups(): Promise<Group[]> {
  const sb = supabase();
  if (!sb) return [];
  const me = await uid();
  if (!me) return [];

  const { data: groups } = await sb
    .from("ah_groups")
    .select("id, name, join_code, created_at")
    .eq("owner_id", me)
    .order("created_at", { ascending: false });
  if (!groups?.length) return [];

  const ids = groups.map((g) => g.id);
  const { data: rows } = await sb
    .from("ah_group_members")
    .select("group_id, student_id, joined_at")
    .in("group_id", ids);

  const studentIds = [...new Set((rows ?? []).map((r) => r.student_id))];
  const names = new Map<string, string>();
  if (studentIds.length) {
    const { data: profs } = await sb.from("ah_profiles").select("id, full_name").in("id", studentIds);
    (profs ?? []).forEach((p) => names.set(p.id, p.full_name ?? ""));
  }

  return groups.map((g) => ({
    ...toGroup(g),
    members: (rows ?? [])
      .filter((r) => r.group_id === g.id)
      .map((r) => ({
        studentId: r.student_id,
        name: names.get(r.student_id) || "unnamed applicant",
        joinedAt: r.joined_at,
      })),
  }));
}

/** A student joins from the code alone — no read access to the group table. */
export async function joinGroup(code: string): Promise<GroupResult<Group>> {
  const sb = supabase();
  if (!sb) return { ok: false, error: "not configured" };
  const trimmed = code.trim();
  if (!trimmed) return { ok: false, error: "enter the code your counselor gave you" };

  const { data, error } = await sb.rpc("ah_join_group", { p_code: trimmed });
  if (error) {
    // a wrong code is the common case, and P0002 is the function's own signal
    return {
      ok: false,
      error: /no group with that code/i.test(error.message)
        ? "no group with that code — check it with your counselor"
        : error.message,
    };
  }
  return { ok: true, value: toGroup(data) };
}

/** The groups a student has joined, with the counselor who runs each. */
export async function listJoinedGroups(): Promise<Group[]> {
  const sb = supabase();
  if (!sb) return [];
  const me = await uid();
  if (!me) return [];

  // RLS returns only the groups this student is a member of
  const { data: groups } = await sb
    .from("ah_groups")
    .select("id, name, join_code, created_at, owner_id")
    .order("created_at", { ascending: false });
  if (!groups?.length) return [];

  const ownerIds = [...new Set(groups.map((g) => g.owner_id))];
  const owners = new Map<string, string>();
  if (ownerIds.length) {
    const { data: profs } = await sb.from("ah_profiles").select("id, full_name").in("id", ownerIds);
    (profs ?? []).forEach((p) => owners.set(p.id, p.full_name ?? ""));
  }

  return groups.map((g) => ({
    ...toGroup(g),
    ownerName: owners.get(g.owner_id) || "your counselor",
  }));
}

/** Leave a group — the student withdraws the counselor's access themselves. */
export async function leaveGroup(groupId: string): Promise<GroupResult<true>> {
  const sb = supabase();
  if (!sb) return { ok: false, error: "not configured" };
  const me = await uid();
  if (!me) return { ok: false, error: "not signed in" };
  const { error } = await sb
    .from("ah_group_members")
    .delete()
    .eq("group_id", groupId)
    .eq("student_id", me);
  return error ? { ok: false, error: error.message } : { ok: true, value: true };
}

/* ── a whole class at a glance ────────────────────────────────────────────── */

export interface StudentSnapshot {
  studentId: string;
  name: string;
  universities: number;
  /** checklist items ticked, out of CHECKLIST.length */
  docsDone: number;
  docsTotal: number;
  portfolio: number;
  deadlines: number;
  nextDeadline: { title: string; date: string } | null;
  exams: string[];
}

/**
 * Progress for every student in a class, in six queries rather than six per head.
 *
 * A counselor with thirty students needs to see who is behind without opening
 * thirty workspaces — and the existing per-student route (`pullStudentWorkspace`)
 * is a full workspace read, which is right for one student and absurd for a class.
 * RLS already lets a counselor read each of these tables for their linked students,
 * so counting per student is one `.in("user_id", ids)` per table and a fold in
 * memory.
 *
 * A student who has not filled in a name is "unnamed applicant" rather than a blank
 * row, because a blank row in a class list reads as a bug in the list.
 */
export async function classSnapshots(studentIds: string[]): Promise<Map<string, StudentSnapshot>> {
  const out = new Map<string, StudentSnapshot>();
  const sb = supabase();
  if (!sb) return out;
  const ids = [...new Set(studentIds)];
  if (ids.length === 0) return out;

  const [profs, unis, checks, port, dls, exams] = await Promise.all([
    sb.from("ah_profiles").select("id, full_name").in("id", ids),
    sb.from("ah_university_lists").select("user_id").in("user_id", ids),
    sb.from("ah_checklist").select("user_id, done").in("user_id", ids),
    sb.from("ah_portfolio").select("user_id").in("user_id", ids),
    sb.from("ah_deadlines").select("user_id, title, due_on").in("user_id", ids),
    sb.from("ah_exam_results").select("user_id, exam_id, overall").in("user_id", ids),
  ]);

  for (const id of ids) {
    out.set(id, {
      studentId: id,
      name: "unnamed applicant",
      universities: 0,
      docsDone: 0,
      docsTotal: CHECKLIST.length,
      portfolio: 0,
      deadlines: 0,
      nextDeadline: null,
      exams: [],
    });
  }

  for (const p of profs.data ?? []) {
    const s = out.get(p.id);
    if (s && p.full_name) s.name = p.full_name;
  }
  for (const r of unis.data ?? []) {
    const s = out.get(r.user_id);
    if (s) s.universities++;
  }
  for (const r of checks.data ?? []) {
    const s = out.get(r.user_id);
    if (s && r.done) s.docsDone++;
  }
  for (const r of port.data ?? []) {
    const s = out.get(r.user_id);
    if (s) s.portfolio++;
  }
  for (const r of exams.data ?? []) {
    const s = out.get(r.user_id);
    if (s) s.exams.push(`${r.exam_id.toUpperCase()}${r.overall ? ` ${r.overall}` : ""}`);
  }

  const today = new Date();
  const todayISO = `${today.getFullYear()}-${String(today.getMonth() + 1).padStart(2, "0")}-${String(today.getDate()).padStart(2, "0")}`;
  for (const r of dls.data ?? []) {
    const s = out.get(r.user_id);
    if (!s) continue;
    s.deadlines++;
    if (r.due_on >= todayISO && (!s.nextDeadline || r.due_on < s.nextDeadline.date)) {
      s.nextDeadline = { title: r.title, date: r.due_on };
    }
  }

  return out;
}

/** Days until an ISO date, negative when it has passed. */
export const daysUntil = (iso: string, now: Date = new Date()): number =>
  Math.ceil((+new Date(iso + "T00:00:00") - +now) / 86_400_000);
